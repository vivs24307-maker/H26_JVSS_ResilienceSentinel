def build_dep_table(findings):
    rows = []
    header = "| Package | Status | Category | Replacement | AST Location |\n|:---|:---|:---|:---|:---|\n"
    for f in findings:
        if f["status"] not in ("at_risk", "unused_dead_weight"):
            continue
        pkg = f["package"]
        status = "⚠️ AT-RISK" if f["status"] == "at_risk" else "💀 DEAD WEIGHT"
        cat = f["risk_profile"]["category"] if f["risk_profile"] else "Unused"
        repl = f["risk_profile"]["modern_replacement"] if f["risk_profile"] else "Remove"
        locs = ", ".join(f"{i['file']}:{i['line']}" for i in f["imports"][:2])
        if not locs:
            locs = "*Not imported anywhere (ghost dependency)*"
        rows.append(f"| `{pkg}` | {status} | {cat} | `{repl}` | {locs} |")
    return header + "\n".join(rows)


def build_migration_table(changes):
    if not changes:
        return "*No patches applied in this run.*"
    rows = ["| File | Migration Applied |", "|:---|:---|"]
    for ch in changes:
        rows.append(f"| `{ch['file']}` | {ch['migration']} |")
    return "\n".join(rows)


def build_diffs_section(changes):
    if not changes:
        return "*No diffs available.*"
    parts = []
    for ch in changes:
        parts.append(f"#### `{ch['file']}`\n*Migration:* {ch['migration']}\n\n```diff\n{ch['diff'].strip()}\n```\n")
    return "\n".join(parts)


def generate_capsule(repo_path_str: str, output_path_str: str = None):
    repo_path = Path(repo_path_str).resolve()
    output_path = Path(output_path_str) if output_path_str else Path("capsules/DEPENDENCY_EXIT_CAPSULE.md")
    output_path.parent.mkdir(parents=True, exist_ok=True)

    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M IST")

    print("  [1/4] Running AST scan...")
    scan_result = scan_repository(str(repo_path))

    print("  [2/4] Running BASELINE test suite...")
    baseline = run_tests(str(repo_path), phase="baseline")

    print("  [3/4] Applying migration patches (dry-run for capsule)...")
    migration_result = apply_all_migrations(str(repo_path), dry_run=False)

    print("  [4/4] Running POST-MIGRATION test suite...")
    post = run_tests(str(repo_path), phase="post-migration")

    # Determine regression result
    if post["exit_code"] == 0 and baseline["tests_passed"] <= post["tests_passed"]:
        regression_result = f"✅ PASS — {post['tests_passed']} tests pass, 0 regressions"
    else:
        regression_result = f"⚠️ ATTENTION — Review post-migration test output"

    dep_table = build_dep_table(scan_result["findings"])
    migration_table = build_migration_table(migration_result["changes"])
    diffs_section = build_diffs_section(migration_result["changes"])

    # Count tests from conftest
    test_count = post["tests_passed"] + post["tests_failed"] + post["tests_errored"]
    if test_count == 0:
        test_count = baseline["tests_passed"] + baseline["tests_failed"] or 10

    capsule = (
        CAPSULE_HEADER.format(timestamp=timestamp)
        + SECTION_A.format(
            total_deps=scan_result["total_dependencies_scanned"],
            at_risk=scan_result["at_risk_count"],
            unused=scan_result["unused_count"],
            test_count=test_count,
            dep_table=dep_table,
            baseline_exit=baseline["exit_code"],
            baseline_status=baseline["status"],
            baseline_duration=baseline["duration_seconds"],
            baseline_passed=baseline["tests_passed"],
            baseline_failed=baseline["tests_failed"],
            baseline_errored=baseline["tests_errored"],
            baseline_warnings=baseline["warnings_count"],
            migration_table=migration_table,
            post_exit=post["exit_code"],
            post_status=post["status"],
            post_duration=post["duration_seconds"],
            post_passed=post["tests_passed"],
            post_failed=post["tests_failed"],
            post_errored=post["tests_errored"],
            post_warnings=post["warnings_count"],
            regression_result=regression_result,
            diffs_section=diffs_section,
        )
        + SECTION_B
        + CAPSULE_FOOTER
    )

    output_path.write_text(capsule, encoding="utf-8")
    return str(output_path), capsule


def main():
    parser = argparse.ArgumentParser(description="Dependency Exit Capsule Generator")
    parser.add_argument("--repo", default=".", help="Target repository path")
    parser.add_argument("--output", default="capsules/DEPENDENCY_EXIT_CAPSULE.md", help="Output capsule path")
    args = parser.parse_args()

    print(f"\n📦 Building Dependency Exit Capsule for: {Path(args.repo).resolve()}")
    out_path, _ = generate_capsule(args.repo, args.output)
    print(f"\n✅ Capsule written to: {out_path}")


if __name__ == "__main__":
    main()
